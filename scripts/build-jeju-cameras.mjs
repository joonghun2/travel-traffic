// Builds src/data/jejuCameras.ts from the Visit Jeju safety camera list (data.go.kr 15150508).
// usage: node --env-file=.env.local scripts/build-jeju-cameras.mjs
// Keeps active cameras with valid coordinates; viewer links are switched to https.
import { writeFileSync } from 'node:fs';

const KEY = process.env.DATA_GO_KR_SERVICE_KEY;
if (!KEY) throw new Error('DATA_GO_KR_SERVICE_KEY is not set');

const url = `https://api.odcloud.kr/api/15150508/v1/uddi:3d5f189d-3dda-4037-ab46-cc2e6a8c066b?page=1&perPage=500&serviceKey=${encodeURIComponent(KEY)}`;
const data = await (await fetch(url)).json();

// The list has one row per camera angle; keep one entry per location with its angle count.
const byLocation = new Map();
const cameras = (data.data || [])
  .filter((c) => c['사용여부'] === 'y')
  .map((c) => ({
    id: String(c['안전관광카메라아이디']),
    name: String(c['안전관광카메라설치위치']).trim(),
    address: String(c['안전관광카메라설치주소'] ?? '').trim(),
    lat: Number(c['위도']),
    lng: Number(c['경도']),
    url: String(c['카메라영상연결경로']).replace(/^http:\/\//, 'https://'),
  }))
  // Jeju lies within 33.0-33.7 N, 126.0-127.0 E; some rows have swapped or empty coordinates.
  .filter((c) => c.lat > 33 && c.lat < 33.7 && c.lng > 126 && c.lng < 127 && c.url.startsWith('https://'))
  .filter((c) => {
    const k = `${c.name}|${c.lat.toFixed(5)}|${c.lng.toFixed(5)}`;
    const first = byLocation.get(k);
    if (first) {
      first.count++;
      return false;
    }
    c.count = 1;
    byLocation.set(k, c);
    return true;
  })
  .sort((a, b) => a.name.localeCompare(b.name, 'ko'));

const lines = cameras.map((c) => `  ${JSON.stringify(c)},`);
writeFileSync(
  'src/data/jejuCameras.ts',
  [
    '// Visit Jeju safety cameras (Jeju Tourism Organization, data.go.kr 15150508).',
    '// GENERATED by scripts/build-jeju-cameras.mjs; do not edit by hand.',
    "import { JejuCamera } from '@/types';",
    '',
    'export const JEJU_CAMERAS: JejuCamera[] = [',
    ...lines,
    '];',
    '',
  ].join('\n')
);
console.log('locations:', cameras.length, '| angles:', cameras.reduce((n, c) => n + c.count, 0), 'of', data.totalCount, '| viewer links:', new Set(cameras.map((c) => c.url)).size);
