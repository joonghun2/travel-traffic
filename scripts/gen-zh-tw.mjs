// Generates src/lib/i18n/zh-tw.ts (Traditional Chinese, Taiwan) from zh-cn.ts:
// OpenCC cn -> twp (characters + Taiwan vocabulary), then term overrides.
// usage: node scripts/gen-zh-tw.mjs   (input/output are drafts for review)
import { readFileSync, writeFileSync } from 'node:fs';
import * as OpenCC from 'opencc-js';

const convert = OpenCC.Converter({ from: 'cn', to: 'twp' });

// Taiwan usage that differs from a character-level conversion.
const OVERRIDES = [
  ['二維碼', 'QR Code'],
  ['質量', '品質'],
  ['公交', '大眾運輸'],
  ['出租車', '計程車'],
  ['掃一掃', '掃描'],
  ['優酷', 'YouTube'],
  ['人氣', '熱門'],
  ['硬核', '高難度'],
  ['撤銷', '復原'],
  ['新窗口', '新視窗'],
  ['窗口', '視窗'],
  ['谷歌地圖', 'Google 地圖'],
  ['城市鐵路', '都市鐵道'],
  ['最佳遊覽時間', '最佳參觀時間'],
  ['推薦遊覽時間', '推薦參觀時間'],
];

const src = readFileSync('src/lib/i18n/zh-cn.ts', 'utf8');
const body = src.slice(src.indexOf('= {') + 2, src.lastIndexOf('}') + 1);
const zhCn = Function(`return ${body}`)();

const zhTw = Object.fromEntries(
  Object.entries(zhCn).map(([k, v]) => {
    let t = convert(v);
    for (const [from, to] of OVERRIDES) t = t.split(from).join(to);
    return [k, t];
  })
);

const lines = Object.entries(zhTw).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`);
writeFileSync(
  'src/lib/i18n/zh-tw.ts',
  [
    '// Traditional Chinese (Taiwan) UI strings. GENERATED by scripts/gen-zh-tw.mjs from zh-cn.ts',
    '// (OpenCC cn->twp + Taiwan term overrides). Draft for review; edit zh-cn.ts or OVERRIDES and regenerate.',
    'export const ZH_TW: Record<string, string> = {',
    ...lines,
    '};',
    '',
  ].join('\n')
);
console.log('zh-tw keys:', Object.keys(zhTw).length);
